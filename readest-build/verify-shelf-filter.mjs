#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]??'upstream','apps/readest-app/src');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const shelf=read('app/library/components/Bookshelf.tsx');
const stream=read('app/library/components/BookshelfStream.tsx');
const dropdown=read('app/library/components/PersonalShelfDropdown.tsx');
const status=read('app/library/components/SetStatusAlert.tsx');
const catalog=read('utils/personalShelfStatuses.ts');
const settings=read('utils/personalI18n.ts');
assert.match(shelf,/enabled: s\.id === RECENT_BOOKSHELF_ID \? true : s\.enabled/);
assert.match(shelf,/section\.items\.length > 0 \|\| section\.definition\.id === RECENT_BOOKSHELF_ID/);
assert.match(shelf,/allBooks=\{visibleBooks\}/);
assert.match(stream,/definition\.id === RECENT_BOOKSHELF_ID \? \(/);
assert.match(stream,/<PersonalShelfDropdown/);
assert.doesNotMatch(stream,/<select className='select select-ghost select-xs ms-3'/);
assert.match(stream,/matchesPersonalStatus\(book, personalShelfFilter\)/);
assert.match(dropdown,/<MdDragHandle size=\{22\}/);
assert.match(dropdown,/useSensor\(TouchSensor/);
assert.match(dropdown,/persistStatusCatalog\(next\)/);
assert.match(dropdown,/createPortal\(/);
assert.match(status,/usePersonalStatusCatalog\(books\)/);
assert.match(status,/catalogItems\(catalog\)\s*\.filter\(\(?item\)?\s*=>\s*item\.assignable\)/);
assert.doesNotMatch(status,/Mark as Reading|Mark as Finished|Mark as Unread/);
assert.match(status,/appendCustomStatus\(catalog, customName\)/);
assert.match(shelf,/onApplyStatus=\{applyPersonalStatus\}/);
assert.match(shelf,/onDeleteCustomStatus=\{deletePersonalStatus\}/);
assert.match(catalog,/recent: '최근 읽은 책'/);
assert.match(catalog,/writing: '작성 중'/);
assert.match(catalog,/required: CORE\.has\(id\)/);
assert.match(catalog,/ReadestStatus:/);
assert.match(settings,/'Read books':\s*'읽은 책'/);
console.log('Status shelf selector: no duplicate heading, draggable single catalog, protected presets and synced bulk actions verified.');

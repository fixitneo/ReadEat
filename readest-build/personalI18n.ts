export function personalTranslate(
  key: string,
  language: string | undefined,
  params?: Readonly<Record<string, string | number>>,
  nativeTranslation?: (key: string) => string,
): string {
  const base = /^ko(?:-|$)/i.test(language ?? '')
    ? (PERSONAL_KO[key] ?? nativeTranslation?.(key) ?? key)
    : (nativeTranslation?.(key) ?? key);
  return base.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_match, name: string) =>
    params?.[name] === undefined ? '{' + name + '}' : String(params[name]));
}
export const usePersonalT = () => {
  const { t, i18n } = useTranslation();
  const language = i18n.resolvedLanguage || i18n.language;
  return useCallback((key: string, params?: Record<string, string | number>) =>
    personalTranslate(key, language, params, (message) =>
      String(t(message, { defaultValue: message }))), [language, t]);
};

/** For strings inserted by source patches into existing translated screens. */
export const personalText = (key: string, params?: Record<string, string | number>) =>
  personalTranslate(key, i18nInstance.resolvedLanguage || i18nInstance.language, params,
    (message) => String(i18nInstance.t(message, { defaultValue: message })));
